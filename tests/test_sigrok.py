"""Pulse-width observation: clean signals measure clean, junk measures to nothing."""
import pytest

from hwcontract.sigrok_adapter import observe, read_csv, runs, synth

DT = 1e9 / 24_000_000


def by_name(obs):
    return {o["name"]: o["value"] for o in obs}


def test_synth_signal_measures_near_nominal():
    obs = by_name(observe(synth(DT), DT))
    assert abs(obs["T0H"] - 350) < DT * 2
    assert abs(obs["T1H"] - 700) < DT * 2
    assert obs["RESET"] > 50000


def test_every_edge_has_a_positive_width():
    for o in observe(synth(DT), DT):
        assert o["value"] > 0


def test_constant_level_capture_yields_no_bit_observations():
    # an idle-low line reports only RESET (the whole capture is one long low run);
    # an idle-high line has no low pulses at all, so nothing at all
    assert [o["name"] for o in observe([0] * 1000, DT)] == ["RESET"]
    assert observe([1] * 1000, DT) == []


def test_tiny_capture_yields_no_observations():
    assert observe([0, 1], DT) == []


def test_runs_counts_transitions():
    assert runs([0, 0, 1, 1, 0], 10) == [(0, 20), (1, 20), (0, 10)]


def test_outlier_pulse_does_not_move_the_median():
    clean = synth(DT)
    dirty = synth(DT)
    # corrupt one 0-bit high pulse (samples ~8-9 long) into a 1-bit-length pulse
    i = 3  # inside the first '0' bit high pulse
    for j in range(i, i + 25):
        dirty[j] = 1
    a = by_name(observe(clean, DT))
    b = by_name(observe(dirty, DT))
    assert abs(a["T0H"] - b["T0H"]) <= DT * 2, "median must be robust to a single glitch"


def test_read_csv_rejects_junk_lines(tmp_path):
    p = tmp_path / "cap.csv"
    p.write_text("0\n1\n1\nhello\n\n0\n")
    with pytest.raises(ValueError, match="line 4: expected one 0 or 1"):
        read_csv(str(p))


@pytest.mark.parametrize("header", ["logic", "DATA"])
def test_read_csv_preserves_sigrok_preamble_and_all_samples(tmp_path, header):
    p = tmp_path / "cap.csv"
    p.write_text("; CSV generated by libsigrok 0.5.2\n"
                 "; from demo on Thu Oct 15\n; Channels (1/8): DATA\n"
                 "; Samplerate: 24 MHz\n" + header + "\n0\n1\n\n1\n0\n")
    assert read_csv(p) == [0, 1, 1, 0]


@pytest.mark.parametrize("text", ["", "# comment\n; comment\n", "logic\n",
                                  "Time,D0\n0,0\n1,1\n", "0\n1,0\n1\n",
                                  "0\n2\n1\n", "0\nlogic\n1\n"])
def test_empty_or_unsupported_csv_fails_explicitly(tmp_path, text):
    p = tmp_path / "cap.csv"
    p.write_text(text)
    with pytest.raises(ValueError, match="no samples|expected one 0 or 1"):
        read_csv(p)


@pytest.mark.parametrize("fn", [runs, observe])
@pytest.mark.parametrize("samples", [[], [0, 2, 1], ["0", "1"], [0, None, 1]])
def test_pulse_ingestion_rejects_empty_and_non_binary_samples(fn, samples):
    with pytest.raises(ValueError, match="no samples|expected 0 or 1"):
        fn(samples, 10)


@pytest.mark.parametrize("value", [0, -1, float("nan"), float("inf"), True, "bad"])
def test_invalid_sample_duration_and_rate_are_rejected(value):
    from hwcontract.sigrok_adapter import sample_period
    with pytest.raises(ValueError, match="dt_ns must be a positive finite"):
        observe([0, 1], value)
    with pytest.raises(ValueError, match="samplerate must be a positive finite"):
        sample_period(value)


def test_fractional_samplerate_is_not_truncated():
    from hwcontract.sigrok_adapter import sample_period
    assert sample_period(2.5) == 400_000_000
    assert sample_period("2.5") == 400_000_000


def test_capture_validates_output_and_parameters(monkeypatch):
    from types import SimpleNamespace
    from hwcontract import sigrok_adapter
    monkeypatch.setattr(sigrok_adapter.subprocess, "run", lambda *a, **kw:
                        SimpleNamespace(stdout="; sigrok output\nlogic\n0\n1\n0\n"))
    assert sigrok_adapter.capture("demo", "D0", 24_000_000, 3) == [0, 1, 0]
    monkeypatch.setattr(sigrok_adapter.subprocess, "run", lambda *a, **kw:
                        SimpleNamespace(stdout="logic\n0\nx\n1\n"))
    with pytest.raises(ValueError, match="sigrok-cli output: line 3"):
        sigrok_adapter.capture("demo", "D0", 24_000_000, 3)
    with pytest.raises(ValueError, match="samplerate"):
        sigrok_adapter.capture("demo", "D0", 0, 3)
    with pytest.raises(ValueError, match="samples must be a positive integer"):
        sigrok_adapter.capture("demo", "D0", 24_000_000, 1.5)


@pytest.mark.parametrize("args,text,diagnostic", [
    (["--samplerate", "0"], "0\n1\n", "samplerate must be a positive finite"),
    (["--samplerate", "24000000"], "Time,D0\n0,1\n", "line 1: expected one 0 or 1"),
    ([], "", "no samples"),
])
def test_adapter_cli_input_errors_have_no_traceback(tmp_path, args, text, diagnostic):
    import subprocess
    import sys
    p = tmp_path / "cap.csv"
    p.write_text(text)
    result = subprocess.run([sys.executable, "-m", "hwcontract.sigrok_adapter",
                             "--csv", str(p), *args], capture_output=True, text=True)
    assert result.returncode != 0
    assert diagnostic in result.stderr
    assert "Traceback" not in result.stderr
    assert not result.stdout


def test_numeric_sigrok_channel_label_is_not_silently_removed(tmp_path):
    p = tmp_path / "cap.csv"
    p.write_text("; Channels (1/8): 0\nlogic\n0\n1\n0\n")
    assert read_csv(p) == [0, 1, 0]
    p.write_text("; Channels (1/8): 0\n0\n1\n0\n")
    with pytest.raises(ValueError, match="ambiguous numeric channel label"):
        read_csv(p)
